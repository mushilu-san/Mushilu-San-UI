#!/usr/bin/env node
// scripts/sync-light-theme.mjs
// Writes src/content/light-theme.ts: every colour token from the light `:root` block of
// projects/ui/src/styles/tokens.css, with palette references resolved to literal values.
// The theme playground uses it so its preview stays light even when the page is dark.
// Re-run after changing tokens.css:  node projects/docs/scripts/sync-light-theme.mjs

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..', '..');
const tokensFile = join(root, 'projects', 'ui', 'src', 'styles', 'tokens.css');
const outFile = join(here, '..', 'src', 'content', 'light-theme.ts');

const css = readFileSync(tokensFile, 'utf8');
// The light theme is the first `:root { ... }` block. Dark overrides come later in the file.
const start = css.indexOf(':root {');
const end = css.indexOf('\n}', start);
if (start < 0 || end < 0) throw new Error('no light :root block in tokens.css');
const block = css.slice(start, end);

const decls = new Map();
for (const m of block.matchAll(/(--mui-[a-z0-9-]+):\s*([^;]+);/g)) decls.set(m[1], m[2].trim());

const resolve = (value, depth = 0) => {
  const ref = /var\((--mui-[a-z0-9-]+)\)/.exec(value);
  if (!ref || depth > 10) return value;
  const target = decls.get(ref[1]);
  if (target === undefined) throw new Error(`unresolved ${ref[1]}`);
  return resolve(value.replace(ref[0], resolve(target, depth + 1)), depth + 1);
};

const colours = [...decls.keys()].filter((name) => name.startsWith('--mui-color-'));
const entries = colours.map((name) => [name, resolve(decls.get(name))]);

const body = entries.map(([n, v]) => `  '${n}': '${v}',`).join('\n');
writeFileSync(
  outFile,
  `// Generated by projects/docs/scripts/sync-light-theme.mjs from tokens.css. Do not edit by hand.
export const LIGHT_THEME: Readonly<Record<string, string>> = {
${body}
};
`,
);
console.log(`sync-light-theme: ${entries.length} colour tokens → ${outFile}`);
