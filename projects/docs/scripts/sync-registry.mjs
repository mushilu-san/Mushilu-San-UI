#!/usr/bin/env node
// scripts/sync-registry.mjs
// Regenerates src/content/registry.ts from the component docs files, so the
// registry cannot drift from them. Run after adding or renaming a docs page:
//   node projects/docs/scripts/sync-registry.mjs
// The registry consistency spec (`npm run test:docs`) still checks the result.

import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const contentDir = join(here, '..', 'src', 'content');
const componentsDir = join(contentDir, 'components');
const registryFile = join(contentDir, 'registry.ts');
const groupsFile = join(contentDir, 'groups.ts');

const groupOrder = [...readFileSync(groupsFile, 'utf8').matchAll(/id: '([^']+)'/g)].map(
  (m) => m[1],
);

function field(source, key) {
  const m = source.match(new RegExp(`(?:^|\\n)\\s*${key}:\\s*'([^']*)'`));
  if (!m) throw new Error(`missing ${key}`);
  return m[1];
}

const entries = [];
const documentedClasses = new Set();
for (const dir of readdirSync(componentsDir).sort()) {
  const file = join(componentsDir, dir, `${dir}.docs.ts`);
  if (!existsSync(file)) continue;
  const src = readFileSync(file, 'utf8');
  for (const m of src.match(/apiClasses: \[([^\]]*)\]/)?.[1].matchAll(/'([A-Za-z0-9]+)'/g) ?? [])
    documentedClasses.add(m[1]);
  entries.push({
    slug: field(src, 'slug'),
    name: field(src, 'name'),
    group: field(src, 'group'),
    summary: field(src, 'summary'),
    file: dir,
  });
}

entries.sort(
  (a, b) =>
    groupOrder.indexOf(a.group) - groupOrder.indexOf(b.group) || a.name.localeCompare(b.name),
);

const body = entries
  .map(
    (e) => `  {
    slug: '${e.slug}',
    name: '${e.name}',
    group: '${e.group}',
    summary: '${e.summary}',
    load: () => import('./components/${e.file}/${e.file}.docs').then((m) => m.doc),
  },`,
  )
  .join('\n');

const out = `import type { RegistryEntry } from './types';

// Generated by projects/docs/scripts/sync-registry.mjs. Edit the docs files, then re-run it.
export const REGISTRY: readonly RegistryEntry[] = [
${body}
];

export function findEntry(
  slug: string,
  registry: readonly RegistryEntry[] = REGISTRY,
): RegistryEntry | undefined {
  return registry.find((e) => e.slug === slug);
}
`;

writeFileSync(registryFile, out);

// Keep the allowlist of not-yet-documented classes in step with the pages.
const undocumentedFile = join(contentDir, 'undocumented.json');
const undocumented = JSON.parse(readFileSync(undocumentedFile, 'utf8')).filter(
  (c) => !documentedClasses.has(c),
);
writeFileSync(undocumentedFile, JSON.stringify(undocumented, null, 2) + '\n');
console.log(`sync-registry: ${entries.length} components → ${registryFile}`);
